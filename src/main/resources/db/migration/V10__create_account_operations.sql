-- feature 15: every change of a balance, with the balance after it.
-- operations are recorded from this version on, earlier deposits and bets are not copied here
CREATE TABLE account_operations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL REFERENCES users (id),
    type          VARCHAR(20)    NOT NULL,
    -- positive - money came to the balance, negative - went from it
    amount        NUMERIC(14, 2) NOT NULL CHECK (amount <> 0),
    balance_after NUMERIC(14, 2) NOT NULL CHECK (balance_after >= 0),
    description   VARCHAR(255)   NOT NULL,
    created_at    TIMESTAMP      NOT NULL
);

CREATE INDEX ix_account_operations_user ON account_operations (user_id, created_at);
