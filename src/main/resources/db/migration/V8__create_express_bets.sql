-- feature 8: express bet - several events in one coupon, odds are multiplied
CREATE TABLE express_bets
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL REFERENCES users (id),
    odds          NUMERIC(14, 2) NOT NULL CHECK (odds > 1),
    amount        NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    potential_win NUMERIC(20, 2) NOT NULL,
    status        VARCHAR(10)    NOT NULL,
    placed_at     TIMESTAMP      NOT NULL
);

CREATE TABLE express_legs
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    express_id BIGINT        NOT NULL REFERENCES express_bets (id),
    event_id   BIGINT        NOT NULL REFERENCES events (id),
    outcome    VARCHAR(10)   NOT NULL,
    odds       NUMERIC(6, 2) NOT NULL,
    UNIQUE (express_id, event_id)
);

CREATE INDEX ix_express_bets_user ON express_bets (user_id);
CREATE INDEX ix_express_legs_event ON express_legs (event_id);
