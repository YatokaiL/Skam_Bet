CREATE TABLE events
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport      VARCHAR(20)   NOT NULL,
    home_team  VARCHAR(255)  NOT NULL,
    away_team  VARCHAR(255)  NOT NULL,
    start_time TIMESTAMP     NOT NULL,
    odds_home  NUMERIC(6, 2) NOT NULL CHECK (odds_home > 1),
    -- null when there is no draw in the sport
    odds_draw  NUMERIC(6, 2) CHECK (odds_draw > 1),
    odds_away  NUMERIC(6, 2) NOT NULL CHECK (odds_away > 1)
);

CREATE INDEX ix_events_start_time ON events (start_time);
CREATE INDEX ix_events_sport_start_time ON events (sport, start_time);
