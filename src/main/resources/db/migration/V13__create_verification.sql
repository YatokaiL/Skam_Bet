-- feature 19: verification of identity, withdrawals are possible only for verified users
ALTER TABLE users
    ADD COLUMN verified_at TIMESTAMP;

CREATE TABLE verification_requests
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id),
    file_name     VARCHAR(255) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    file_size     INT          NOT NULL CHECK (file_size > 0),
    status        VARCHAR(10)  NOT NULL,
    reject_reason VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL,
    reviewed_at   TIMESTAMP
);

-- the file itself is kept apart, so lists of requests don't load documents
CREATE TABLE verification_documents
(
    request_id BIGINT PRIMARY KEY REFERENCES verification_requests (id),
    content    BYTEA NOT NULL
);

CREATE INDEX ix_verification_requests_user ON verification_requests (user_id, created_at);
-- a user can't have two requests under review at once
CREATE UNIQUE INDEX ux_verification_requests_pending ON verification_requests (user_id) WHERE status = 'PENDING';
